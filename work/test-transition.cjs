const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('script.js', 'utf8');
for (const viewport of [[1280,720], [390,844], [320,568], [1920,1080]]) {
  let callback;
  let strokes = 0;
  let fills = [];
  const gradients = [];
  const ctx = {setTransform(){}, clearRect(){strokes=0;fills=[];}, strokeRect(){strokes++;}, fillRect(...args){fills.push(args);}, createLinearGradient(...coords){const gradient={coords,stops:[],addColorStop(...stop){this.stops.push(stop);}};gradients.push(gradient);return gradient;}};
  const makeNode = (attrs = {}) => ({ hidden:false, attrs, events:{}, dataset:{}, classList:{contains:()=>false}, setAttribute(k,v){this.attrs[k]=v;}, removeAttribute(k){delete this.attrs[k];}, getAttribute(k){return this.attrs[k];}, focus(options){this.focusOptions=options;}, addEventListener(k,fn){this.events[k]=fn;} });
  const nodes = Object.fromEntries(['#intro','#destination','#play','#enter','#transition-status','#previous-screen','#next-screen','#screen-count','#screen-label'].map(k=>[k,makeNode()]));
  nodes['#destination'].hidden = true;
  const screens = ['accueil','accompagnement','methode','mailys','contact'].map(id=>Object.assign(makeNode(),{id,dataset:{title:id}}));
  const links = screens.map(screen=>makeNode({href:`#${screen.id}`}));
  nodes['#transition'] = {getContext:()=>ctx};
  const media = {matches:false,addEventListener(){}};
  const documentEvents = {};
  const windowEvents = {};
  const location = {hash:''};
  const historyCalls = [];
  const sandbox = {document:{hidden:false,querySelector:k=>nodes[k],querySelectorAll:k=>k==='.screen'?screens:links,addEventListener:(name,fn)=>{documentEvents[name]=fn;}}, window:{innerWidth:viewport[0],innerHeight:viewport[1],devicePixelRatio:2,location,history:{pushState(a,b,hash){historyCalls.push(hash);location.hash=hash;}},addEventListener:(name,fn)=>{windowEvents[name]=fn;}}, matchMedia:()=>media, requestAnimationFrame:()=>1, cancelAnimationFrame(){}, setTimeout:fn=>{callback=fn;return 1;}, clearTimeout(){}};
  vm.createContext(sandbox);
  vm.runInContext(source,sandbox);
  const run = expr => vm.runInContext(expr,sandbox);
  assert.deepEqual(gradients[0].coords,[0,0,...viewport]);
  assert.deepEqual(gradients[0].stops,[[0,'#FF6B6B'],[.5,'#E11D2A'],[1,'#F97316']]);
  run('scheduleIntro()'); callback();
  assert.equal(nodes['#play'].disabled,true);
  run('frame(0)');
  run('frame(COVERED - 1)');
  assert.equal(nodes['#destination'].hidden,true);
  run('frame(COVERED)');
  assert.equal(nodes['#destination'].hidden,false);
  assert.equal(strokes, 0, 'No grid strokes at full coverage');
  assert.deepEqual(fills, [[0, 0, ...viewport]], 'One continuous full-screen fill');
  run('draw(COVERED + HOLD)');
  assert.equal(strokes, 0, 'No grid at the start of the reveal');
  assert.equal(run('tiles.every(t => ease((COVERED - t.delay) / GROW) === 1)'),true);
  assert.equal(run('tiles[0].x <= 0 && tiles[0].y <= 0'),true);
  assert.equal(run('tiles.at(-1).x + tiles.at(-1).size >= width && tiles.at(-1).y + tiles.at(-1).size >= height'),true);
  run('frame(DURATION)');
  assert.equal(nodes['#play'].disabled,false);
  run('start(); frame(0); frame(650)');
  assert.equal(nodes['#intro'].hidden,false);
  assert.equal(run('elapsed'),0,'Replay holds the logo before starting');
  run('frame(850)');
  assert.equal(run('elapsed'),200);
  run('start()');
  assert.equal(run('elapsed'),200,'Repeated activation does not restart an active animation');
  sandbox.document.hidden=true;
  documentEvents.visibilitychange();
  run('frame(20000)');
  assert.equal(run('elapsed'),200,'Hidden tabs pause the animation');
  sandbox.document.hidden=false;
  documentEvents.visibilitychange();
  run('frame(20000); frame(20100)');
  assert.equal(run('elapsed'),300,'Resume has no time jump');
  assert.equal(nodes['#destination'].hidden,true);
  run('layout()');
  assert.equal(run('elapsed'),300,'Resize preserves playback position');
  run('frame(25000)');
  assert.equal(nodes['#play'].disabled,false);
  assert.equal(strokes,0);
  assert.deepEqual(fills,[],'The canvas is completely clear after completion');
  assert.equal(screens.filter(s=>!s.hidden).length,1,'Exactly one screen visible');
  assert.equal(nodes['#previous-screen'].disabled,true,'Previous disabled on first screen');
  nodes['#next-screen'].events.click();
  run('frame(0); frame(COVERED - 1)');
  assert.equal(screens[0].hidden,false,'Keep the outgoing screen until the wipe covers it');
  assert.equal(nodes['#intro'].hidden,true,'No intro flash between sections');
  assert.equal(nodes['#destination'].hidden,false,'The site stays visible during section navigation');
  run('frame(COVERED)');
  assert.equal(screens[1].hidden,false);
  assert.equal(screens.filter(s=>!s.hidden).length,1);
  assert.equal(strokes,0,'Section changes preserve the grid-free wipe');
  run('frame(DURATION)');
  assert.equal(location.hash,'#accompagnement');
  assert.equal(screens[1].focusOptions.preventScroll,true);
  assert.equal(links[1].attrs['aria-current'],'page');
  assert.equal(links[0].attrs['aria-current'],undefined);
  assert.equal(nodes['#screen-count'].textContent,'02 / 05');
  assert.equal(nodes['#previous-screen'].disabled,false);
  assert.equal(run('running'),false);
  run('navigateTo(4); frame(0)');
  location.hash='#methode';
  windowEvents.popstate();
  run('frame(DURATION); frame(0); frame(DURATION)');
  assert.equal(run('currentScreen'),2,'Back/forward during an active transition ends at the latest route');
  media.matches=true;
  links[4].events.click({preventDefault(){},button:0});
  assert.equal(screens[4].hidden,false,'Direct links also work with reduced motion');
  assert.equal(nodes['#next-screen'].disabled,true,'Next disabled on the last screen');
  assert.equal(historyCalls.at(-1),'#contact');
  const count = historyCalls.length;
  location.hash='#mailys';
  windowEvents.hashchange();
  assert.equal(run('currentScreen'),3);
  assert.equal(historyCalls.length,count,'History navigation does not push another entry');
  documentEvents.keydown({key:'ArrowLeft',target:{closest:()=>null},preventDefault(){}});
  assert.equal(run('currentScreen'),2,'Left/right keyboard navigation');
  run('navigateTo(-1); navigateTo(5)');
  assert.equal(run('currentScreen'),2,'No out of range screens');
  run('start()');
  assert.equal(nodes['#play'].disabled,false);
  assert.equal(nodes['#destination'].hidden,false);
  console.log(`PASS ${viewport.join('x')}: gradient, no grid, coverage, autoplay, replay, pause/resume, resize, fixed screens, links, arrows, history, focus, reduced motion`);
}
